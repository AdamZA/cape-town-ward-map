// Generate TypeScript types from ../schemas/*.schema.json (exported by `wardmap schemas`).
// One module per schema in src/generated/. Output is committed; CI regenerates and fails on diff.
import { compile } from "json-schema-to-typescript";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const schemas = new URL("../../schemas/", import.meta.url);
const out = new URL("../src/generated/", import.meta.url);

// Pydantic gives every property a "title", which makes the generator emit an alias per field
// (`export type Label = string`). Strip property titles so fields are typed inline; keep model
// titles so interfaces keep their names.
function stripPropertyTitles(node) {
  if (Array.isArray(node)) return node.forEach(stripPropertyTitles);
  if (!node || typeof node !== "object") return;
  if (node.properties) {
    for (const prop of Object.values(node.properties)) {
      if (prop && typeof prop === "object" && !prop.$ref && prop.type !== "object") delete prop.title;
      if (prop && typeof prop === "object" && (prop.anyOf || prop.items || prop.additionalProperties))
        delete prop.title;
    }
  }
  for (const v of Object.values(node)) stripPropertyTitles(v);
}

for (const file of readdirSync(schemas).filter((f) => f.endsWith(".schema.json")).sort()) {
  const schema = JSON.parse(readFileSync(new URL(file, schemas), "utf8"));
  stripPropertyTitles(schema);
  const ts = await compile(schema, schema.title, {
    bannerComment: `/* Generated by scripts/gen-types.mjs from schemas/${file}. Do not edit. */`,
    additionalProperties: false,
    style: { singleQuote: false },
  });
  const name = file.replace(".schema.json", ".ts");
  writeFileSync(new URL(name, out), ts);
  console.log(`wrote src/generated/${name}`);
}
